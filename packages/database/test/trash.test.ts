import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import test from 'node:test';
import { DomainError } from '@ecs/domain';
import { CatalogDatabase, MIGRATIONS, TRASH_RETENTION_DAYS } from '../src/index.js';
import { companionDirectory, companionExtension, companionStem } from '../src/source-companions.js';

const DAY = 86_400_000;

function problem(code: string) {
  return (error: unknown) => error instanceof DomainError && error.code === code;
}

async function withCatalog(
  run: (catalog: CatalogDatabase, filename: string) => void | Promise<void>,
  limits: ConstructorParameters<typeof CatalogDatabase>[1] = {},
): Promise<void> {
  const dir = await mkdtemp(join(tmpdir(), 'ecs-trash-'));
  const filename = join(dir, 'library.sqlite');
  const catalog = new CatalogDatabase(filename, limits);
  try {
    await run(catalog, filename);
  } finally {
    catalog.close();
    await rm(dir, { recursive: true, force: true });
  }
}

function seed(catalog: CatalogDatabase) {
  const user = catalog.createUser({
    username: 'owner',
    passwordHash: 'not-a-password-hash',
    actorId: 'test',
  });
  const library = catalog.createLibrary(user.id, 'Library');
  const item = catalog.createItem({
    libraryId: library.id,
    systemIdentifier: 'com.provenance.nes',
    title: 'Example',
    md5: null,
    crc: null,
    actorId: user.id,
  });
  return { user, library, item };
}

/** Records a file whose digest comes from generated bytes. No bytes are stored here. */
function addFile(
  catalog: CatalogDatabase,
  userId: string,
  libraryId: string,
  itemId: string,
  relativePath: string,
  bytes: Buffer = randomBytes(24),
) {
  const upload = catalog.createUpload({ userId, guestGrantId: null, libraryId });
  const item = catalog.getItem(itemId);
  assert.ok(item);
  return catalog.completeUpload({
    uploadId: upload.id,
    itemId,
    kind: 'rom',
    displayName: relativePath,
    relativePath,
    baseRevision: item.revision,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    size: bytes.length,
    md5: createHash('md5').update(bytes).digest('hex'),
    crc: '00000000',
    shareable: true,
    actorId: userId,
    locationId: null,
  });
}

const later = (days: number) => new Date(Date.now() + days * DAY).toISOString();

test('version 23 keeps live and deleted rows, dates old deletions from the upgrade, and opens twice', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'ecs-trash-migrate-'));
  const filename = join(dir, 'library.sqlite');
  try {
    const prior = new DatabaseSync(filename);
    prior.function('ecs_companion_parent', { deterministic: true }, (value) =>
      companionDirectory(String(value ?? '')),
    );
    prior.function('ecs_companion_stem', { deterministic: true }, (value) =>
      companionStem(String(value ?? '')),
    );
    prior.function('ecs_companion_extension', { deterministic: true }, (value) =>
      companionExtension(String(value ?? '')),
    );
    for (const migration of MIGRATIONS.filter((entry) => entry.version <= 22)) {
      prior.exec(migration.sql);
      prior.prepare('INSERT INTO schema_migrations VALUES (?, ?)').run(migration.version, 'now');
    }
    const longAgo = '2020-01-01T00:00:00.000Z';
    prior.exec(`INSERT INTO users VALUES ('owner','owner','fixture',1,'now');
      INSERT INTO libraries VALUES ('library','Library','owner',1,'now',NULL);
      INSERT INTO items VALUES ('live','library','com.provenance.nes','Live',NULL,NULL,1,'now','now',NULL);
      INSERT INTO items VALUES ('gone','library','com.provenance.nes','Gone',NULL,NULL,2,'now','now','${longAgo}');
      INSERT INTO blobs(sha256,size,created_at) VALUES ('${'a'.repeat(64)}',3,'now');
      INSERT INTO assets(id,item_id,kind,display_name,relative_path,sha256,size,shareable,revision,created_at,updated_at,deleted_at)
        VALUES ('gone-file','gone','rom','gone.nes','gone.nes','${'a'.repeat(64)}',3,1,1,'now','now','${longAgo}');`);
    prior.close();
    const before = Date.now();
    for (let open = 0; open < 2; open++) {
      const upgraded = new CatalogDatabase(filename);
      try {
        assert.equal(upgraded.integrity(), 'ok');
        assert.equal(upgraded.getItem('live')?.title, 'Live');
        const entries = upgraded.listTrash({ libraryId: null, after: null, limit: 10 }).entries;
        assert.deepEqual(
          entries.map((entry) => [entry.kind, entry.id, entry.deletedBy]),
          [['item', 'gone', null]],
        );
        const purgeAfter = Date.parse(entries[0]?.purgeAfter ?? '');
        assert.ok(purgeAfter >= before + (TRASH_RETENTION_DAYS - 1) * DAY, 'not purged on upgrade');
        assert.deepEqual(upgraded.purgeExpired(new Date().toISOString(), 100), {
          items: 0,
          files: 0,
          openUploads: [],
        });
      } finally {
        upgraded.close();
      }
    }
    const raw = new DatabaseSync(filename, { readOnly: true });
    const stamps = raw.prepare('SELECT purge_after FROM items WHERE id=?').get('gone');
    raw.close();
    assert.ok(stamps?.purge_after, 'the second open left the date alone');
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('deleting a game records who and until when, and restoring returns the files that went with it', async () => {
  await withCatalog((catalog) => {
    const { user, library, item } = seed(catalog);
    const kept = addFile(catalog, user.id, library.id, item.id, 'game.nes');
    const earlier = addFile(catalog, user.id, library.id, item.id, 'notes.txt');
    assert.equal(catalog.deleteAsset(earlier.id, user.id), true);
    assert.equal(catalog.deleteItem(item.id, user.id), true);

    const entries = catalog.listTrash({ libraryId: library.id, after: null, limit: 10 }).entries;
    assert.deepEqual(entries.map((entry) => `${entry.kind}:${entry.id}`).sort(), [
      `file:${earlier.id}`,
      `item:${item.id}`,
    ]);
    const game = entries.find((entry) => entry.kind === 'item');
    assert.equal(game?.name, 'Example');
    assert.equal(game?.deletedBy, user.id);
    assert.equal(game?.deletedByName, 'owner');
    assert.equal(game?.fileCount, 1);
    assert.equal(game?.size, kept.size);
    assert.equal(
      Date.parse(game?.purgeAfter ?? '') - Date.parse(game?.deletedAt ?? ''),
      TRASH_RETENTION_DAYS * DAY,
    );

    assert.throws(() => catalog.restoreAsset(earlier.id, user.id), problem('conflict'));

    const before = catalog.changes({
      after: 0,
      limit: 500,
      libraryIds: [library.id],
      includeSensitive: true,
      itemId: null,
    }).changes.length;
    const restored = catalog.restoreItem(item.id, user.id);
    assert.equal(restored.id, item.id);
    assert.equal(catalog.getAsset(kept.id)?.id, kept.id);
    assert.equal(
      catalog.getAsset(earlier.id),
      null,
      'a file deleted on its own stays in the trash',
    );
    const after = catalog.changes({
      after: 0,
      limit: 500,
      libraryIds: [library.id],
      includeSensitive: true,
      itemId: null,
    }).changes;
    assert.deepEqual(
      after.slice(before).map((change) => `${change.entityType}:${change.op}`),
      ['item:upsert', 'asset:upsert'],
    );
    assert.equal(catalog.restoreItem(item.id, user.id).id, item.id, 'restoring twice is harmless');
    assert.equal(catalog.restoreAsset(earlier.id, user.id).id, earlier.id);
    assert.deepEqual(catalog.listTrash({ libraryId: null, after: null, limit: 10 }).entries, []);
    assert.equal(catalog.auditContains('restore-item', item.id), false);
  });
});

test('a restored file never takes the place of a newer file at the same path', async () => {
  await withCatalog((catalog) => {
    const { user, library, item } = seed(catalog);
    const old = addFile(catalog, user.id, library.id, item.id, 'game.nes');
    catalog.deleteAsset(old.id, user.id);
    const newer = addFile(catalog, user.id, library.id, item.id, 'game.nes');
    const restored = catalog.restoreAsset(old.id, user.id);
    assert.equal(restored.conflictOf, newer.id);
    assert.notEqual(restored.relativePath, newer.relativePath);
    assert.equal(catalog.getAsset(newer.id)?.relativePath, 'game.nes');
    assert.equal(restored.sha256, old.sha256);
  });
});

test('restoring past the library quota is refused and leaves the trash unchanged', async () => {
  await withCatalog(
    (catalog) => {
      const { user, library, item } = seed(catalog);
      const first = addFile(catalog, user.id, library.id, item.id, 'a.nes', randomBytes(30));
      catalog.deleteAsset(first.id, user.id);
      addFile(catalog, user.id, library.id, item.id, 'b.nes', randomBytes(30));
      assert.throws(() => catalog.restoreAsset(first.id, user.id), problem('quota-exceeded'));
      assert.equal(
        catalog.listTrash({ libraryId: null, after: null, limit: 10 }).entries.length,
        1,
      );
    },
    { maxLibraryBytes: 50 },
  );
});

test('the trash lists newest first and pages without repeating', async () => {
  await withCatalog((catalog) => {
    const { user, library, item } = seed(catalog);
    const ids: string[] = [];
    for (let index = 0; index < 5; index++) {
      const file = addFile(catalog, user.id, library.id, item.id, `f${index}.nes`);
      catalog.deleteAsset(file.id, user.id);
      ids.push(file.id);
    }
    const seen: string[] = [];
    let after: { deletedAt: string; id: string } | null = null;
    for (let page = 0; page < 5; page++) {
      const result = catalog.listTrash({ libraryId: null, after, limit: 2 });
      seen.push(...result.entries.map((entry) => entry.id));
      after = result.next;
      if (!after) break;
    }
    assert.deepEqual([...seen].sort(), [...ids].sort());
    assert.equal(new Set(seen).size, 5);
  });
});

test('purge removes only what is past its date and a blob stays while any file row names it', async () => {
  await withCatalog((catalog) => {
    const { user, library, item } = seed(catalog);
    const shared = randomBytes(24);
    const live = addFile(catalog, user.id, library.id, item.id, 'live.nes', shared);
    const twin = addFile(catalog, user.id, library.id, item.id, 'twin.nes', shared);
    const lonely = addFile(catalog, user.id, library.id, item.id, 'lonely.nes');
    catalog.deleteAsset(twin.id, user.id);
    catalog.deleteAsset(lonely.id, user.id);

    assert.deepEqual(catalog.unreferencedBlobs(10), [], 'the trash still holds the bytes');
    assert.equal(catalog.forgetBlob(lonely.sha256), false);
    assert.deepEqual(catalog.purgeExpired(later(TRASH_RETENTION_DAYS - 1), 100), {
      items: 0,
      files: 0,
      openUploads: [],
    });
    assert.equal(catalog.restoreAsset(twin.id, user.id).id, twin.id);
    catalog.deleteAsset(twin.id, user.id);

    const purged = catalog.purgeExpired(later(TRASH_RETENTION_DAYS + 1), 100);
    assert.equal(purged.files, 2);
    assert.equal(purged.items, 0);
    assert.throws(() => catalog.restoreAsset(lonely.id, user.id), problem('not-found'));
    assert.deepEqual(
      catalog.unreferencedBlobs(10).map((blob) => blob.sha256),
      [lonely.sha256],
    );
    assert.equal(catalog.forgetBlob(live.sha256), false, 'a live file still names it');
    assert.equal(catalog.forgetBlob(lonely.sha256), true);
    assert.deepEqual(catalog.unreferencedBlobs(10), []);
    assert.equal(catalog.getAsset(live.id)?.sha256, live.sha256);
    assert.equal(catalog.auditContains('purge', lonely.sha256), false);
    assert.equal(catalog.integrity(), 'ok');
  });
});

test('purging a game removes its access rows and guest links, and reports unfinished uploads', async () => {
  await withCatalog((catalog) => {
    const { user, library, item } = seed(catalog);
    const other = seed0(catalog, library.id, user.id);
    addFile(catalog, user.id, library.id, item.id, 'game.nes');
    const grant = catalog.createGuestGrant({
      tokenHash: 'not-a-token-hash',
      libraryId: library.id,
      itemId: item.id,
      capabilities: ['write'],
      expiresAt: later(1),
      createdBy: user.id,
    });
    const pending = catalog.createUpload({
      userId: null,
      guestGrantId: grant.id,
      libraryId: library.id,
    });
    catalog.deleteItem(item.id, user.id);
    const purged = catalog.purgeExpired(later(TRASH_RETENTION_DAYS + 1), 100);
    assert.deepEqual(purged, { items: 1, files: 1, openUploads: [pending.id] });
    assert.equal(catalog.getItem(item.id), null);
    assert.equal(catalog.getUpload(pending.id), null);
    assert.equal(catalog.getItem(other.id)?.title, 'Other', 'a live game is untouched');
    assert.equal(catalog.integrity(), 'ok');
    assert.deepEqual(catalog.purgeExpired(later(TRASH_RETENTION_DAYS + 1), 100), {
      items: 0,
      files: 0,
      openUploads: [],
    });
  });
});

function seed0(catalog: CatalogDatabase, libraryId: string, userId: string) {
  return catalog.createItem({
    libraryId,
    systemIdentifier: 'com.provenance.nes',
    title: 'Other',
    md5: null,
    crc: null,
    actorId: userId,
  });
}

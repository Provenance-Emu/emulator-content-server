import { identifyRom } from '../src/rom-identification.js';

const run = promisify(execFile),
  seven = process.env.ECS_IDENTIFY_7Z ?? '/opt/homebrew/bin/7zz',
  chdman = process.env.ECS_IDENTIFY_CHDMAN ?? '/opt/homebrew/bin/chdman';
async function present(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}
async function archive(
  directory: string,
  name: string,
  members: string[],
  options: string[] = [],
  creator = seven,
) {
  const path = join(directory, name);
  await run(creator, ['a', '-t7z', '-mmt=1', '-mx=1', '-ms=off', ...options, path, ...members], {
    cwd: directory,
  });
  const size = (await import('node:fs/promises')).stat(path).then((s) => s.size);
  return { path, name, systemId: null, size: await size, tools: { sevenZip: seven } };
}
test('native 7z fingerprints one regular inner ROM without a staged extraction', async (t) => {
  if (!(await present(seven)))
    return t.skip('Configure ECS_IDENTIFY_7Z for generated native acceptance.');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-identify-7z-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await writeFile(join(directory, 'generated.j64'), '123456789');
  await writeFile(join(directory, 'readme.txt'), 'Generated bytes only');
  const input = await archive(directory, 'single.7z', ['generated.j64', 'readme.txt']);
  const facts = await identifyRom(input);
  assert.equal(facts.hashes.find((hash) => hash.algorithm === 'crc32')?.value, 'cbf43926');
  assert.ok(
    facts.hashes.every(
      (hash) =>
        hash.verified && hash.size === 9 && hash.representation === '7z-member:generated.j64',
    ),
  );
  assert.deepEqual(facts.warnings, []);
  assert.deepEqual(facts.names, ['generated.j64']);
});
test('native 7z rejects multiple ROMs, solid blocks, encryption and symbolic-link members', async (t) => {
  if (!(await present(seven)))
    return t.skip('Configure ECS_IDENTIFY_7Z for generated native acceptance.');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-identify-7z-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await writeFile(join(directory, 'a.j64'), 'first generated payload');
  await writeFile(join(directory, 'b.j64'), 'second generated payload');
  await writeFile(join(directory, 'readme.txt'), 'Generated metadata');
  for (const input of [
    await archive(directory, 'multiple.7z', ['a.j64', 'b.j64']),
    await archive(directory, 'solid.7z', ['a.j64', 'readme.txt'], ['-ms=on']),
    await archive(directory, 'encrypted.7z', ['a.j64'], ['-pfixture-password']),
  ]) {
    const facts = await identifyRom(input);
    assert.deepEqual(facts.hashes, []);
    assert.ok(facts.warnings.length);
  }
  await writeFile(join(directory, 'target'), '123456789');
  await symlink('target', join(directory, 'link.j64'));
  const linked = await identifyRom(
    await archive(
      directory,
      'linked.7z',
      ['link.j64'],
      ['-snl'],
      (await present('/opt/homebrew/bin/7zz')) ? '/opt/homebrew/bin/7zz' : seven,
    ),
  );
  assert.deepEqual(linked.hashes, []);
  assert.ok(linked.warnings.length);
});
function isoRecord(lba: number, size: number, name: Buffer, directory = false): Buffer {
  const length = 33 + name.length + (name.length % 2 === 0 ? 1 : 0),
    record = Buffer.alloc(length);
  record[0] = length;
  record.writeUInt32LE(lba, 2);
  record.writeUInt32BE(lba, 6);
  record.writeUInt32LE(size, 10);
  record.writeUInt32BE(size, 14);
  record[25] = directory ? 2 : 0;
  record.writeUInt16LE(1, 28);
  record.writeUInt16BE(1, 30);
  record[32] = name.length;
  name.copy(record, 33);
  return record;
}
test('native CHD slice identification reads a generated Dreamcast header and PS1 ISO SYSTEM.CNF without whole-image expansion', async (t) => {
  if (!(await present(chdman)))
    return t.skip('Configure ECS_IDENTIFY_CHDMAN for generated native acceptance.');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-identify-chd-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const dc = Buffer.alloc(64 * 2048);
  dc.write('SEGA SEGAKATANA ', 0, 'ascii');
  dc.write('SEGA ENTERPRISES', 16, 'ascii');
  dc.write('T-12345N', 0x40, 'ascii');
  dc.write('Generated homebrew', 0x80, 'ascii');
  const psx = Buffer.alloc(64 * 2048);
  const pvd = psx.subarray(16 * 2048, 17 * 2048);
  pvd[0] = 1;
  pvd.write('CD001', 1, 'ascii');
  pvd[6] = 1;
  pvd.writeUInt16LE(2048, 128);
  pvd.writeUInt16BE(2048, 130);
  isoRecord(20, 2048, Buffer.from([0]), true).copy(pvd, 156);
  const config = Buffer.from('BOOT = cdrom:\\SLUS_123.45;1\r\n');
  isoRecord(21, config.length, Buffer.from('SYSTEM.CNF;1')).copy(psx, 20 * 2048);
  config.copy(psx, 21 * 2048);
  const naomi = Buffer.from(dc),
    naomi2 = Buffer.from(dc);
  naomi.fill(0, 0x40, 0x4a);
  naomi.write('GDL-0018', 0x40, 'ascii');
  naomi2.fill(0, 0x40, 0x4a);
  naomi2.write('GDS-0014', 0x40, 'ascii');
  for (const [name, bytes, serial, system] of [
    ['dc', dc, 'T-12345N', 'com.provenance.dreamcast'],
    ['naomi', naomi, 'GDL-0018', null],
    ['naomi2', naomi2, 'GDS-0014', null],
    ['psx', psx, 'SLUS-12345', 'com.provenance.psx'],
  ] as const) {
    const raw = join(directory, `${name}.bin`),
      path = join(directory, `${name}.chd`);
    await writeFile(raw, bytes);
    await run(chdman, [
      'createraw',
      '-i',
      raw,
      '-o',
      path,
      '-hs',
      '4096',
      '-us',
      '2048',
      '-c',
      'none',
    ]);
    const size = (await import('node:fs/promises')).stat(path).then((s) => s.size);
    const facts = await identifyRom({
      path,
      name: `${name}.chd`,
      systemId: null,
      size: await size,
      tools: { chdman },
    });
    assert.equal(facts.identifiers[0]?.value, serial, JSON.stringify(facts));
    assert.equal(facts.identifiers[0]?.verified, true);
    assert.equal(facts.identifiers[0]?.systemId, system);
    assert.ok(facts.hashes.every((hash) => !hash.verified));
  }
});
test('native helpers bound stdout and cancellation kills and joins a process that ignores SIGTERM', async (t) => {
  if (process.platform === 'win32') return t.skip('POSIX generated executable acceptance.');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-identify-tool-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.j64'),
    tool = join(directory, 'helper');
  await writeFile(path, '123456789');
  await writeFile(tool, `#!${process.execPath}\nprocess.stdout.write(Buffer.alloc(100000));`);
  await chmod(tool, 0o755);
  const input = { path, name: 'generated.j64', systemId: null, size: 9, tools: { sevenZip: tool } };
  const facts = await identifyRom(input, undefined, [
    {
      id: 'test.tool',
      supports: () => true,
      identify: async (_request, reader) => {
        await reader.runTool('sevenZip', [], { maxStdoutBytes: 10 });
        return { version: 1, pluginIds: [], hashes: [], identifiers: [], names: [], warnings: [] };
      },
    },
  ]);
  assert.ok(facts.warnings.includes('test.tool:unsupported-or-unavailable'));
  await writeFile(
    tool,
    `#!${process.execPath}\nprocess.on('SIGTERM',()=>{});process.stdout.write(String(process.pid));setInterval(()=>{},1000);`,
  );
  let pid = 0;
  const abort = new AbortController();
  await assert.rejects(
    identifyRom(input, abort.signal, [
      {
        id: 'test.tool',
        supports: () => true,
        identify: async (_request, reader) => {
          await reader.runTool('sevenZip', [], {
            maxStdoutBytes: 64,
            onStdout: (bytes) => {
              pid = Number(Buffer.from(bytes).toString());
              abort.abort();
            },
          });
          return {
            version: 1,
            pluginIds: [],
            hashes: [],
            identifiers: [],
            names: [],
            warnings: [],
          };
        },
      },
    ]),
    { name: 'AbortError' },
  );
  assert.ok(pid > 0);
  assert.throws(() => process.kill(pid, 0), { code: 'ESRCH' });
});

test('native CHD readers honor standard MODE1 CD frames and current GD metadata PAD placement', async (t) => {
  if (!(await present(chdman)))
    return t.skip('Configure ECS_IDENTIFY_CHDMAN for generated native acceptance.');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-identify-disc-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const iso = Buffer.alloc(64 * 2048),
    pvd = iso.subarray(16 * 2048, 17 * 2048);
  pvd[0] = 1;
  pvd.write('CD001', 1, 'ascii');
  pvd[6] = 1;
  pvd.writeUInt16LE(2048, 128);
  pvd.writeUInt16BE(2048, 130);
  isoRecord(20, 2048, Buffer.from([0]), true).copy(pvd, 156);
  const config = Buffer.from('BOOT = cdrom:\\SLUS_123.45;1\r\n');
  isoRecord(21, config.length, Buffer.from('SYSTEM.CNF;1')).copy(iso, 20 * 2048);
  config.copy(iso, 21 * 2048);
  await writeFile(join(directory, 'psx.bin'), iso);
  await writeFile(
    join(directory, 'psx.cue'),
    'FILE "psx.bin" BINARY\n TRACK 01 MODE1/2048\n INDEX 01 00:00:00\n',
  );
  const cd = join(directory, 'psx.chd');
  await run(chdman, ['createcd', '-i', join(directory, 'psx.cue'), '-o', cd]);
  let size = await (await import('node:fs/promises')).stat(cd).then((info) => info.size);
  let result = await identifyRom({
    path: cd,
    name: 'psx.chd',
    systemId: null,
    size,
    tools: { chdman },
  });
  assert.equal(result.identifiers[0]?.value, 'SLUS-12345', JSON.stringify(result));
  const logical = Buffer.alloc(16 * 2448);
  logical.write('SEGA SEGAKATANA ', 4 * 2448, 'ascii');
  logical.write('T-12345N', 4 * 2448 + 0x40, 'ascii');
  await writeFile(join(directory, 'gd.raw'), logical);
  const gd = join(directory, 'gd.chd');
  await run(chdman, [
    'createraw',
    '-i',
    join(directory, 'gd.raw'),
    '-o',
    gd,
    '-hs',
    String(4 * 2448),
    '-us',
    '2448',
    '-c',
    'none',
  ]);
  for (const [index, text] of [
    'TRACK:1 TYPE:AUDIO SUBTYPE:NONE FRAMES:4 PAD:0 PREGAP:0 PGTYPE:AUDIO PGSUB:NONE POSTGAP:0',
    'TRACK:2 TYPE:MODE1 SUBTYPE:NONE FRAMES:12 PAD:0 PREGAP:0 PGTYPE:MODE1 PGSUB:NONE POSTGAP:0',
  ].entries())
    await run(chdman, ['addmeta', '-i', gd, '-t', 'CHGD', '-ix', String(index), '-vt', text]);
  size = await (await import('node:fs/promises')).stat(gd).then((info) => info.size);
  result = await identifyRom({ path: gd, name: 'gd.chd', systemId: null, size, tools: { chdman } });
  assert.equal(result.identifiers[0]?.value, 'T-12345N', JSON.stringify(result));
});

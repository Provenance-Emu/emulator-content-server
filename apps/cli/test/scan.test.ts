import assert from 'node:assert/strict';
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import test from 'node:test';
import { CatalogDatabase } from '@ecs/database';

type Actor = Parameters<CatalogDatabase['listContentRootSummaries']>[0]['actor'];

import { backupData, doctor, initData, listRoots, scanRoots } from '../src/lifecycle.js';
import { readBootstrapped } from '../src/service.js';

async function fixture() {
  const base = await realpath(await mkdtemp(join(tmpdir(), 'ecs-cli-scan-')));
  const dataDir = join(base, 'data');
  await initData(dataDir, 'Test');
  const catalog = new CatalogDatabase(join(dataDir, 'library.sqlite'));
  const owner = catalog.createUser({ username: 'owner', passwordHash: 'fixture', actorId: 'test' });
  const library = catalog.createLibrary(owner.id, 'Library');
  const actor: Actor = {
    kind: 'user',
    userId: owner.id,
    username: 'owner',
    isOwner: true,
    tokenKind: 'session',
    deviceId: null,
    scopes: ['read'],
  };
  const root = async (label: string) => {
    const path = join(base, label);
    await mkdir(path);
    await writeFile(join(path, 'generated.nes'), 'generated bytes');
    return catalog.createContentRoot({ path, label, libraryId: library.id, actorId: owner.id });
  };
  return {
    base,
    dataDir,
    catalog,
    actor,
    root,
    summary(id: string) {
      return catalog.listContentRootSummaries({ actor }).find((row) => row.id === id);
    },
    async close() {
      catalog.close();
      await rm(base, { recursive: true, force: true });
    },
  };
}

test('CLI selected scan completes fresh and failed summaries without scanning unrelated roots', async () => {
  const f = await fixture();
  try {
    const root = await f.root('selected');
    const other = await f.root('untouched');
    const scanning = scanRoots(f.dataDir, root.id);
    assert.equal(f.summary(root.id)?.scanState, 'pending');
    assert.throws(
      () => f.catalog.beginRootScan(root.id),
      (error: unknown) => error instanceof Error && 'code' in error && error.code === 'conflict',
    );
    const results = await scanning;
    assert.equal(results.length, 1);
    assert.equal(results[0]?.online, true);
    assert.equal(results[0]?.count, 1);
    const summary = f.summary(root.id);
    assert.equal(summary?.scanState, 'completed');
    assert.equal(summary?.availability, 'online');
    assert.ok(summary?.lastCheckedAt);
    assert.ok(summary?.lastScanStartedAt);
    assert.ok(summary?.lastScanCompletedAt);
    assert.equal(summary?.medium, results[0]?.medium);
    assert.equal(summary?.scanError, null);
    assert.equal(summary?.indexedFileCount, 1);
    assert.equal(f.summary(other.id)?.scanState, 'unknown');
    assert.equal(f.summary(other.id)?.indexedFileCount, 0);
    assert.equal(f.summary(other.id)?.lastCheckedAt, null);
    f.catalog.beginRootScan(root.id);
    f.catalog.finishRootScan({ rootId: root.id, succeeded: false });
    await scanRoots(f.dataDir, root.id);
    assert.equal(f.summary(root.id)?.scanState, 'completed');
    assert.equal(f.summary(root.id)?.scanError, null);
    await rm(root.path, { recursive: true });
    const offline = await scanRoots(f.dataDir, root.id);
    assert.equal(offline[0]?.online, false);
    assert.equal(offline[0]?.count, 1);
    assert.equal(f.summary(root.id)?.indexedFileCount, 1);
    assert.equal(f.catalog.listSources(root.id)[0]?.availability, 'offline');
    assert.equal(f.summary(root.id)?.availability, 'offline');
    assert.equal(f.summary(root.id)?.scanState, 'completed');
    assert.equal(f.summary(root.id)?.medium, offline[0]?.medium);
    assert.equal(f.summary(root.id)?.scanError, null);
  } finally {
    await f.close();
  }
});

test('auxiliary CLI operations retain pending ownership and reject duplicate scans', async () => {
  const f = await fixture();
  try {
    const root = await f.root('active');
    f.catalog.beginRootScan(root.id);
    await initData(f.dataDir, 'Test');
    await doctor(f.dataDir);
    await backupData(f.dataDir, join(f.base, 'backup'));
    listRoots(f.dataDir);
    readBootstrapped(f.dataDir);
    assert.equal(f.summary(root.id)?.scanState, 'pending');
    await assert.rejects(
      scanRoots(f.dataDir, root.id),
      (error: unknown) => error instanceof Error && 'code' in error && error.code === 'conflict',
    );
    assert.equal(f.summary(root.id)?.scanState, 'pending');
    assert.equal(f.summary(root.id)?.indexedFileCount, 0);
    assert.equal(f.summary(root.id)?.lastCheckedAt, null);
  } finally {
    await f.close();
  }
});

test('CLI scan failures record safe state before a successful retry', async () => {
  const f = await fixture();
  try {
    const root = await f.root('failure');
    const sql = new DatabaseSync(join(f.dataDir, 'library.sqlite'));
    try {
      sql.exec(
        `CREATE TRIGGER fail_scan BEFORE INSERT ON source_files BEGIN SELECT RAISE(ABORT,'private scan failure ${root.path.replaceAll("'", "''")}'); END;`,
      );
      await assert.rejects(
        scanRoots(f.dataDir, root.id),
        (error: unknown) => error instanceof Error && error.message === 'Scan failed. Retry scan.',
      );
      const summary = f.summary(root.id);
      assert.equal(summary?.scanState, 'failed');
      assert.equal(summary?.scanError, 'Scan failed. Retry scan.');
      assert.ok(summary?.lastScanStartedAt);
      assert.ok(summary?.lastScanCompletedAt);
      assert.equal(summary?.indexedFileCount, 0);
      sql.exec('DROP TRIGGER fail_scan');
      await scanRoots(f.dataDir, root.id);
      assert.equal(f.summary(root.id)?.scanState, 'completed');
      assert.equal(f.summary(root.id)?.scanError, null);
      assert.equal(f.summary(root.id)?.indexedFileCount, 1);
    } finally {
      sql.close();
    }
  } finally {
    await f.close();
  }
});

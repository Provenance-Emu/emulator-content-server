import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { access, rm } from 'node:fs/promises';
import test from 'node:test';
import { TRASH_RETENTION_DAYS } from '@ecs/database';
import { blobPath } from '@ecs/storage';
import { libraryFixture } from './library-fixture.js';

type Fixture = Awaited<ReturnType<typeof libraryFixture>>;
type Headers = Record<string, string>;

const DAY = 86_400_000;
const pastRetention = () => new Date(Date.now() + (TRASH_RETENTION_DAYS + 1) * DAY);

async function exists(path: string): Promise<boolean> {
  return access(path).then(
    () => true,
    () => false,
  );
}

/** Uploads generated bytes through the API so a real blob lands on disk. */
async function upload(
  f: Fixture,
  itemId: string,
  relativePath: string,
  bytes: Buffer,
  headers: Headers = f.auth,
) {
  const created = await f.app.inject({
    method: 'POST',
    url: '/api/v1/uploads',
    headers,
    payload: { libraryId: f.library.id },
  });
  assert.equal(created.statusCode, 201);
  const id = (created.json() as { id: string }).id;
  const put = await f.app.inject({
    method: 'PUT',
    url: `/api/v1/uploads/${id}/content`,
    headers: { ...headers, 'content-type': 'application/octet-stream' },
    payload: bytes,
  });
  assert.equal(put.statusCode, 204);
  const done = await f.app.inject({
    method: 'POST',
    url: `/api/v1/uploads/${id}/complete`,
    headers,
    payload: {
      itemId,
      kind: 'rom',
      displayName: relativePath,
      relativePath,
      baseRevision: f.catalog.getItem(itemId)?.revision,
    },
  });
  assert.equal(done.statusCode, 201, done.body);
  return done.json() as { id: string; sha256: string };
}

async function account(f: Fixture, username: string, role: 'reader' | 'editor' | null) {
  const added = await f.app.inject({
    method: 'POST',
    url: '/api/v1/users',
    payload: { username, password: 'battery-staple' },
  });
  assert.equal(added.statusCode, 201, added.body);
  const id = (added.json() as { id: string }).id;
  if (role) f.catalog.setMember(f.library.id, id, role, f.owner.id);
  const login = await f.app.inject({
    method: 'POST',
    url: '/api/v1/auth/login',
    remoteAddress: '8.8.8.8',
    payload: { username, password: 'battery-staple' },
  });
  assert.equal(login.statusCode, 200);
  return { authorization: `Bearer ${(login.json() as { token: string }).token}` };
}

const away = { remoteAddress: '8.8.8.8' };

test('a deleted game is listed, restored by someone who may write, and its bytes read back', async () => {
  const f = await libraryFixture();
  try {
    const item = f.item('Example');
    const bytes = randomBytes(64);
    const file = await upload(f, item.id, 'game.generated', bytes);
    const reader = await account(f, 'reader', 'reader');
    const stranger = await account(f, 'stranger', null);
    const editor = await account(f, 'editor', 'editor');
    const grant = await f.app.inject({
      method: 'POST',
      url: '/api/v1/guest-grants',
      headers: f.auth,
      payload: {
        libraryId: f.library.id,
        itemId: item.id,
        capabilities: ['read', 'write'],
        expiresInSeconds: 3600,
      },
    });
    assert.equal(grant.statusCode, 201, grant.body);
    const guest = { authorization: `Bearer ${(grant.json() as { token: string }).token}` };

    const removed = await f.app.inject({
      method: 'DELETE',
      url: `/api/v1/items/${item.id}`,
      headers: f.auth,
    });
    assert.equal(removed.statusCode, 204);
    const gone = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${file.id}/content`,
      headers: f.auth,
    });
    assert.equal(gone.statusCode, 404);

    const listed = await f.app.inject({ method: 'GET', url: '/api/v1/trash', headers: f.auth });
    assert.equal(listed.statusCode, 200, listed.body);
    const page = listed.json() as {
      entries: Array<Record<string, unknown>>;
      nextCursor: string | null;
    };
    assert.equal(page.entries.length, 1);
    assert.equal(page.entries[0]?.kind, 'item');
    assert.equal(page.entries[0]?.id, item.id);
    assert.equal(page.entries[0]?.name, 'Example');
    assert.equal(page.entries[0]?.size, bytes.length);
    assert.deepEqual(page.entries[0]?.deletedBy, { id: f.owner.id, name: 'owner' });
    assert.equal(listed.body.includes(file.sha256), false, 'no digests in the trash list');
    assert.equal(page.nextCursor, null);

    const restore = { method: 'POST' as const, url: `/api/v1/items/${item.id}/restore`, ...away };
    assert.equal((await f.app.inject(restore)).statusCode, 401);
    assert.equal((await f.app.inject({ ...restore, headers: stranger })).statusCode, 404);
    assert.equal((await f.app.inject({ ...restore, headers: reader })).statusCode, 403);
    assert.equal((await f.app.inject({ ...restore, headers: guest })).statusCode, 403);
    for (const headers of [reader, stranger, guest]) {
      const seen = await f.app.inject({ method: 'GET', url: '/api/v1/trash', headers, ...away });
      const entries =
        seen.statusCode === 200 ? (seen.json() as { entries: unknown[] }).entries : [];
      assert.deepEqual(entries, [], 'only someone who may restore sees an entry');
    }
    assert.equal(
      (await f.app.inject({ method: 'GET', url: '/api/v1/trash', headers: guest, ...away }))
        .statusCode,
      403,
    );
    assert.equal(
      (
        (
          await f.app.inject({ method: 'GET', url: '/api/v1/trash', headers: editor, ...away })
        ).json() as { entries: unknown[] }
      ).entries.length,
      1,
    );

    const restored = await f.app.inject({ ...restore, headers: editor });
    assert.equal(restored.statusCode, 200, restored.body);
    assert.equal((restored.json() as { id: string }).id, item.id);
    const content = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${file.id}/content`,
      headers: f.auth,
    });
    assert.equal(content.statusCode, 200);
    assert.deepEqual(content.rawPayload, bytes);
    const again = await f.app.inject({ ...restore, headers: editor });
    assert.equal(again.statusCode, 200, 'restoring twice is harmless');
    const empty = await f.app.inject({ method: 'GET', url: '/api/v1/trash', headers: f.auth });
    assert.deepEqual((empty.json() as { entries: unknown[] }).entries, []);
  } finally {
    await f.dispose();
  }
});

test('a deleted file is restored on its own, and not while its game is in the trash', async () => {
  const f = await libraryFixture();
  try {
    const item = f.item('Example');
    const bytes = randomBytes(48);
    const file = await upload(f, item.id, 'save.generated', bytes);
    const reader = await account(f, 'reader', 'reader');
    assert.equal(
      (await f.app.inject({ method: 'DELETE', url: `/api/v1/files/${file.id}`, headers: f.auth }))
        .statusCode,
      204,
    );
    const restore = { method: 'POST' as const, url: `/api/v1/files/${file.id}/restore` };
    assert.equal((await f.app.inject({ ...restore, ...away })).statusCode, 401);
    assert.equal((await f.app.inject({ ...restore, headers: reader, ...away })).statusCode, 403);
    assert.equal(
      (
        await f.app.inject({
          method: 'POST',
          url: '/api/v1/files/not-a-file/restore',
          headers: f.auth,
        })
      ).statusCode,
      404,
    );

    await f.app.inject({ method: 'DELETE', url: `/api/v1/items/${item.id}`, headers: f.auth });
    const blocked = await f.app.inject({ ...restore, headers: f.auth });
    assert.equal(blocked.statusCode, 409);
    await f.app.inject({
      method: 'POST',
      url: `/api/v1/items/${item.id}/restore`,
      headers: f.auth,
    });
    const restored = await f.app.inject({ ...restore, headers: f.auth });
    assert.equal(restored.statusCode, 200, restored.body);
    const content = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${file.id}/content`,
      headers: f.auth,
    });
    assert.deepEqual(content.rawPayload, bytes);
  } finally {
    await f.dispose();
  }
});

test('retention purges only past the date and collects only bytes nothing names', async () => {
  const f = await libraryFixture();
  try {
    const item = f.item('Example');
    const sharedBytes = randomBytes(40);
    const live = await upload(f, item.id, 'live.generated', sharedBytes);
    const twin = await upload(f, item.id, 'twin.generated', sharedBytes);
    const lonely = await upload(f, item.id, 'lonely.generated', randomBytes(40));
    const kept = await upload(f, item.id, 'kept.generated', randomBytes(40));
    assert.equal(live.sha256, twin.sha256);
    for (const id of [twin.id, lonely.id]) {
      await f.app.inject({ method: 'DELETE', url: `/api/v1/files/${id}`, headers: f.auth });
    }
    const lonelyPath = blobPath(`${f.base}/data`, lonely.sha256);
    const sharedPath = blobPath(`${f.base}/data`, live.sha256);
    assert.equal(await exists(lonelyPath), true);

    assert.deepEqual(await f.runRetention(new Date()), { items: 0, files: 0, blobs: 0 });
    assert.equal(await exists(lonelyPath), true, 'bytes in the trash stay on disk');
    const early = await f.app.inject({
      method: 'POST',
      url: `/api/v1/files/${lonely.id}/restore`,
      headers: f.auth,
    });
    assert.equal(early.statusCode, 200);
    await f.app.inject({ method: 'DELETE', url: `/api/v1/files/${lonely.id}`, headers: f.auth });

    assert.deepEqual(await f.runRetention(pastRetention()), { items: 0, files: 2, blobs: 1 });
    assert.equal(await exists(lonelyPath), false);
    assert.equal(await exists(sharedPath), true, 'a live file still names these bytes');
    assert.equal(await exists(blobPath(`${f.base}/data`, kept.sha256)), true);
    const late = await f.app.inject({
      method: 'POST',
      url: `/api/v1/files/${lonely.id}/restore`,
      headers: f.auth,
    });
    assert.equal(late.statusCode, 404);
    const content = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${live.id}/content`,
      headers: f.auth,
    });
    assert.deepEqual(content.rawPayload, sharedBytes);
    assert.deepEqual(await f.runRetention(pastRetention()), { items: 0, files: 0, blobs: 0 });
    assert.equal(f.catalog.auditContains('purge', lonely.sha256), false);
  } finally {
    await f.dispose();
  }
});

test('a blob row whose file is already gone heals, and the same bytes can be uploaded again', async () => {
  const f = await libraryFixture();
  try {
    const item = f.item('Example');
    const bytes = randomBytes(40);
    const first = await upload(f, item.id, 'a.generated', bytes);
    await f.app.inject({ method: 'DELETE', url: `/api/v1/files/${first.id}`, headers: f.auth });
    // The state a stop between unlinking and forgetting leaves behind.
    await rm(blobPath(`${f.base}/data`, first.sha256));
    assert.deepEqual(await f.runRetention(pastRetention()), { items: 0, files: 1, blobs: 1 });
    assert.equal(f.catalog.blobRecord(first.sha256), null);

    const second = await upload(f, item.id, 'a.generated', bytes);
    assert.equal(second.sha256, first.sha256);
    const content = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${second.id}/content`,
      headers: f.auth,
    });
    assert.deepEqual(content.rawPayload, bytes);
  } finally {
    await f.dispose();
  }
});

test('an upload that completes while collection runs keeps its bytes', async () => {
  const f = await libraryFixture();
  try {
    const item = f.item('Example');
    const bytes = randomBytes(40);
    const first = await upload(f, item.id, 'a.generated', bytes);
    await f.app.inject({ method: 'DELETE', url: `/api/v1/files/${first.id}`, headers: f.auth });
    assert.equal(f.catalog.purgeExpired(pastRetention().toISOString(), 10).files, 1);
    // The blob row is now unreferenced. Race a re-upload of the same bytes against collection.
    const [second] = await Promise.all([
      upload(f, item.id, 'b.generated', bytes),
      f.runRetention(pastRetention()),
    ]);
    const content = await f.app.inject({
      method: 'GET',
      url: `/api/v1/files/${second.id}/content`,
      headers: f.auth,
    });
    assert.equal(content.statusCode, 200);
    assert.deepEqual(content.rawPayload, bytes);
  } finally {
    await f.dispose();
  }
});

test('capabilities say how long the trash keeps things', async () => {
  const f = await libraryFixture();
  try {
    const response = await f.app.inject({ method: 'GET', url: '/api/v1/capabilities' });
    assert.deepEqual((response.json() as { trash?: unknown }).trash, {
      retentionDays: TRASH_RETENTION_DAYS,
    });
  } finally {
    await f.dispose();
  }
});

test('root scans and organization exclude each other until root reservations release', async () => {
  const f = await fixture();
  try {
    const preview = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(preview.statusCode, 200, preview.body);
    let release = reserveContentRoots(f.catalog, [f.root.id, f.to.id, f.root.id]);
    try {
      const scan = await f.app.inject({
        method: 'POST',
        url: `/api/v1/roots/${f.to.id}/scan`,
        headers: f.auth,
      });
      assert.equal(scan.statusCode, 409, scan.body);
      const apply = await f.app.inject({
        method: 'POST',
        url: `${f.url}/apply`,
        headers: f.auth,
        payload: { planId: preview.json().planId },
      });
      assert.equal(apply.statusCode, 409, apply.body);
      assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
      assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'generated bytes');
      assert.throws(() => reserveContentRoots(f.catalog, [f.to.id]), /progress/);
    } finally {
      release();
    }
    const scan = await f.app.inject({
      method: 'POST',
      url: `/api/v1/roots/${f.to.id}/scan`,
      headers: f.auth,
    });
    assert.equal(scan.statusCode, 200, scan.body);
    release = reserveContentRoots(f.catalog, [f.to.id]);
    release();
  } finally {
    await f.dispose();
  }
});

test('automatic organization is disabled by default; preview consent enables future moves and disable stops them', async () => {
  const f = await fixture();
  try {
    const { runAutomaticOrganization } = await import('../src/source-organization.js');
    const policyUrl = `/api/v1/roots/${f.root.id}/organization-policy`;
    let response = await f.app.inject({ method: 'GET', url: policyUrl, headers: f.auth });
    assert.equal(response.statusCode, 200, response.body);
    assert.equal(response.json().enabled, false);
    assert.equal(await runAutomaticOrganization(f, f.actor, f.source.id), undefined);
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'generated bytes');
    response = await f.app.inject({
      method: 'PUT',
      url: policyUrl,
      headers: f.auth,
      payload: { enabled: true },
    });
    assert.equal(response.statusCode, 400, response.body);
    response = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    const plan = response.json();
    response = await f.app.inject({
      method: 'PUT',
      url: policyUrl,
      headers: f.auth,
      payload: { enabled: true, planId: plan.planId },
    });
    assert.equal(response.statusCode, 200, response.body);
    // Enabling confirms the policy but does not process existing files.
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
    const result = await runAutomaticOrganization(f, f.actor, f.source.id);
    assert.equal(result?.status, 'moved');
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.to.id);
    response = await f.app.inject({
      method: 'PUT',
      url: policyUrl,
      headers: f.auth,
      payload: { enabled: false },
    });
    assert.equal(response.statusCode, 200, response.body);
    assert.equal(response.json().enabled, false);
    await writeFile(join(f.path, 'untouched.nes'), 'future bytes');
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.root.id}/scan`, headers: f.auth });
    const untouched = f.catalog
      .listSources(f.root.id)
      .find((file) => file.displayName === 'untouched.nes');
    assert.ok(untouched);
    assert.equal(await runAutomaticOrganization(f, f.actor, untouched.id), undefined);
    assert.equal(await readFile(join(f.path, 'untouched.nes'), 'utf8'), 'future bytes');
  } finally {
    await f.dispose();
  }
});


    assert.equal(
      f.catalog.sourceMatches(response.json().sourceId).matches[0]?.title,
      'Matched Title',
    );
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'changed bytes');

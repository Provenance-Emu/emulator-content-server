async function fixture() {
  const f = await libraryFixture();
  const path = join(f.base, 'games');
  const target = join(f.base, 'organized');
  await mkdir(path);
  await mkdir(target);
  await writeFile(join(path, 'generated.nes'), 'generated bytes');
  const root = f.catalog.createContentRoot({
    path,
    label: 'Games',
    libraryId: f.library.id,
    actorId: f.owner.id,
  });
  const to = f.catalog.createContentRoot({
    path: target,
    label: 'Organized',
    libraryId: f.library.id,
    actorId: f.owner.id,
  });
  await f.app.inject({ method: 'POST', url: `/api/v1/roots/${root.id}/scan`, headers: f.auth });
  const source = f.catalog.listSources(root.id)[0];
  assert.ok(source);
  return { ...f, path, target, root, to, source, url: `/api/v1/sources/${source.id}/organization` };
}


import assert from 'node:assert/strict';
import { unlinkSync, writeFileSync } from 'node:fs';
import { lstat, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import test from 'node:test';
import { reserveContentRoots } from '../src/root-mutations.js';
import { libraryFixture } from './library-fixture.js';

async function fixture() {
  const f = await libraryFixture();
  const path = join(f.base, 'games');
  const target = join(f.base, 'organized');
  await mkdir(path);
  await mkdir(target);
  await writeFile(join(path, 'generated.nes'), 'generated bytes');
  const root = f.catalog.createContentRoot({
    path,
    label: 'Games',
    libraryId: f.library.id,
    actorId: f.owner.id,
  });
  const to = f.catalog.createContentRoot({
    path: target,
    label: 'Organized',
    libraryId: f.library.id,
    actorId: f.owner.id,
  });
  await f.app.inject({ method: 'POST', url: `/api/v1/roots/${root.id}/scan`, headers: f.auth });
  const source = f.catalog.listSources(root.id)[0];
  assert.ok(source);
  return { ...f, path, target, root, to, source, url: `/api/v1/sources/${source.id}/organization` };
}

test('organization requires owner; preview is read only and move preserves source ID and metadata', async () => {
  const f = await fixture();
  try {
    const match = f.catalog.saveSourceMatch(
      f.source.id,
      0,
      'metadata',
      {
        id: 'generated-match',
        providerId: 'org.ecs.local',
        kind: 'metadata',
        title: 'Matched Title',
        confidence: 'local',
        metadata: { publisher: 'Generated' },
        originKind: null,
        contentAvailable: false,
        contentType: null,
        fileName: null,
        updatedAt: new Date().toISOString(),
      },
      null,
      f.owner.id,
    );
    const anonymous = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      remoteAddress: '8.8.8.8',
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(anonymous.statusCode, 401, anonymous.body);
    const preview = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(preview.statusCode, 200, preview.body);
    const plan = preview.json();
    assert.equal(plan.targetRelativePath, 'NES/Matched Title/generated.nes');
    assert.ok(!preview.body.includes(f.base));
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'generated bytes');
    const apply = await f.app.inject({
      method: 'POST',
      url: `${f.url}/apply`,
      headers: f.auth,
      payload: { planId: plan.planId },
    });
    assert.equal(apply.statusCode, 200, apply.body);
    assert.equal(apply.json().sourceId, f.source.id);
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.to.id);
    assert.equal(f.catalog.sourceMatches(f.source.id).revision, match.revision);
    assert.equal(f.catalog.sourceMatches(f.source.id).matches[0]?.title, 'Matched Title');
    assert.equal(
      await readFile(join(f.target, plan.targetRelativePath), 'utf8'),
      'generated bytes',
    );
    assert.equal(
      (
        await f.app.inject({
          method: 'POST',
          url: `${f.url}/apply`,
          headers: f.auth,
          payload: { planId: plan.planId },
        })
      ).statusCode,
      409,
    );
  } finally {
    await f.dispose();
  }
});

test('copy indexes a separate source and clones saved matches; stale previews never write', async () => {
  const f = await fixture();
  try {
    f.catalog.saveSourceMatch(
      f.source.id,
      0,
      'metadata',
      {
        id: 'generated-match',
        providerId: 'org.ecs.local',
        kind: 'metadata',
        title: 'Matched Title',
        confidence: 'local',
        metadata: {},
        originKind: null,
        contentAvailable: false,
        contentType: null,
        fileName: null,
        updatedAt: new Date().toISOString(),
      },
      null,
      f.owner.id,
    );
    const preview = async () =>
      f.app.inject({
        method: 'POST',
        url: `${f.url}/preview`,
        headers: f.auth,
        payload: { mode: 'copy', targetRootId: f.to.id },
      });
    let response = await preview();
    assert.equal(response.statusCode, 200, response.body);
    const stale = response.json();
    await writeFile(join(f.path, 'generated.nes'), 'changed bytes');
    response = await f.app.inject({
      method: 'POST',
      url: `${f.url}/apply`,
      headers: f.auth,
      payload: { planId: stale.planId },
    });
    assert.equal(response.statusCode, 409, response.body);
    assert.equal(f.catalog.listSources(f.to.id).length, 0);
    response = await preview();
    assert.equal(response.statusCode, 409, response.body);
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.root.id}/scan`, headers: f.auth });
    response = await preview();
    assert.equal(response.statusCode, 200, response.body);
    response = await f.app.inject({
      method: 'POST',
      url: `${f.url}/apply`,
      headers: f.auth,
      payload: { planId: response.json().planId },
    });
    assert.equal(response.statusCode, 200, response.body);
    assert.notEqual(response.json().sourceId, f.source.id);
    assert.equal(
      f.catalog.sourceMatches(response.json().sourceId).matches[0]?.title,
      'Matched Title',
    );
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'changed bytes');
  } finally {
    await f.dispose();
  }
});

test('organization rejects local trust, foreign libraries, unsupported files and caller paths', async () => {
  const f = await fixture();
  try {
    const request = (payload: unknown) =>
      f.app.inject({
        method: 'POST',
        url: `${f.url}/preview`,
        headers: f.auth,
        payload: payload as object,
      });
    assert.equal(
      (
        await f.app.inject({
          method: 'POST',
          url: `${f.url}/preview`,
          remoteAddress: '192.168.1.20',
          payload: { mode: 'copy', targetRootId: f.to.id },
        })
      ).statusCode,
      403,
    );
    assert.equal(
      (await request({ mode: 'copy', targetRootId: f.to.id, targetRelativePath: '../escape' }))
        .statusCode,
      400,
    );
    const other = f.catalog.createLibrary(f.owner.id, 'Other');
    const foreignPath = join(f.base, 'foreign');
    await mkdir(foreignPath);
    const foreign = f.catalog.createContentRoot({
      path: foreignPath,
      label: 'Foreign',
      libraryId: other.id,
      actorId: f.owner.id,
    });
    assert.equal((await request({ mode: 'copy', targetRootId: foreign.id })).statusCode, 409);
    await writeFile(join(f.path, 'archive.zip'), 'generated archive placeholder');
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.root.id}/scan`, headers: f.auth });
    const archive = f.catalog.listSources(f.root.id).find((s) => s.displayName === 'archive.zip');
    assert.ok(archive);
    assert.equal(
      (
        await f.app.inject({
          method: 'POST',
          url: `/api/v1/sources/${archive.id}/organization/preview`,
          headers: f.auth,
          payload: { mode: 'move', targetRootId: f.to.id },
        })
      ).statusCode,
      409,
    );
  } finally {
    await f.dispose();
  }
});

test('catalog failure rolls back prepared move while keeping original and matches', async () => {
  const f = await fixture();
  try {
    const preview = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(preview.statusCode, 200, preview.body);
    const plan = preview.json();
    const relocate = f.catalog.relocateSource;
    f.catalog.relocateSource = () => {
      throw new Error('generated catalog failure');
    };
    try {
      const result = await f.app.inject({
        method: 'POST',
        url: `${f.url}/apply`,
        headers: f.auth,
        payload: { planId: plan.planId },
      });
      assert.equal(result.statusCode, 500, result.body);
      assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
      assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'generated bytes');
      await assert.rejects(lstat(join(f.target, plan.targetRelativePath)), { code: 'ENOENT' });
    } finally {
      f.catalog.relocateSource = relocate;
    }
  } finally {
    await f.dispose();
  }
});

test('post-commit unlink conflict preserves destination association and reports recovery warning', async () => {
  const f = await fixture();
  try {
    const preview = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(preview.statusCode, 200, preview.body);
    const plan = preview.json();
    const relocate = f.catalog.relocateSource.bind(f.catalog);
    // Replace the original synchronously at the catalog/finalize boundary.
    f.catalog.relocateSource = (input) => {
      const saved = relocate(input);
      unlinkSync(join(f.path, 'generated.nes'));
      writeFileSync(join(f.path, 'generated.nes'), 'replacement');
      return saved;
    };
    const result = await f.app.inject({
      method: 'POST',
      url: `${f.url}/apply`,
      headers: f.auth,
      payload: { planId: plan.planId },
    });
    assert.equal(result.statusCode, 200, result.body);
    assert.ok(result.json().warning);
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.to.id);
    assert.equal(
      await readFile(join(f.target, plan.targetRelativePath), 'utf8'),
      'generated bytes',
    );
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'replacement');
  } finally {
    await f.dispose();
  }
});

test('an unscanned replacement cannot inherit the original identity or saved matches through organization', async () => {
  const f = await fixture();
  try {
    unlinkSync(join(f.path, 'generated.nes'));
    writeFileSync(join(f.path, 'generated.nes'), 'unrelated replacement');
    const response = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(response.statusCode, 409, response.body);
    assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
    assert.equal(f.catalog.listSources(f.to.id).length, 0);
    assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'unrelated replacement');
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.root.id}/scan`, headers: f.auth });
    assert.equal(f.catalog.getSource(f.source.id), null);
    assert.notEqual(f.catalog.listSources(f.root.id)[0]?.id, f.source.id);
  } finally {
    await f.dispose();
  }
});

test('long Unicode names preserve their ROM extension after organize and rescan', async () => {
  const f = await fixture();
  try {
    const longName = `${'語'.repeat(70)}.nes`;
    await writeFile(join(f.path, longName), 'generated long-name bytes');
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.root.id}/scan`, headers: f.auth });
    const source = f.catalog.listSources(f.root.id).find((s) => s.displayName === longName);
    assert.ok(source);
    const url = `/api/v1/sources/${source.id}/organization`;
    let response = await f.app.inject({
      method: 'POST',
      url: `${url}/preview`,
      headers: f.auth,
      payload: { mode: 'copy', targetRootId: f.to.id },
    });
    assert.equal(response.statusCode, 200, response.body);
    const plan = response.json();
    assert.ok(plan.targetRelativePath.endsWith('.nes'));
    response = await f.app.inject({
      method: 'POST',
      url: `${url}/apply`,
      headers: f.auth,
      payload: { planId: plan.planId },
    });
    assert.equal(response.statusCode, 200, response.body);
    const copiedId = response.json().sourceId;
    await f.app.inject({ method: 'POST', url: `/api/v1/roots/${f.to.id}/scan`, headers: f.auth });
    assert.equal(f.catalog.getSource(copiedId)?.kind, 'rom');
  } finally {
    await f.dispose();
  }
});

test('root scans and organization exclude each other until root reservations release', async () => {
  const f = await fixture();
  try {
    const preview = await f.app.inject({
      method: 'POST',
      url: `${f.url}/preview`,
      headers: f.auth,
      payload: { mode: 'move', targetRootId: f.to.id },
    });
    assert.equal(preview.statusCode, 200, preview.body);
    let release = reserveContentRoots(f.catalog, [f.root.id, f.to.id, f.root.id]);
    try {
      const scan = await f.app.inject({
        method: 'POST',
        url: `/api/v1/roots/${f.to.id}/scan`,
        headers: f.auth,
      });
      assert.equal(scan.statusCode, 409, scan.body);
      const apply = await f.app.inject({
        method: 'POST',
        url: `${f.url}/apply`,
        headers: f.auth,
        payload: { planId: preview.json().planId },
      });
      assert.equal(apply.statusCode, 409, apply.body);
      assert.equal(f.catalog.getSource(f.source.id)?.rootId, f.root.id);
      assert.equal(await readFile(join(f.path, 'generated.nes'), 'utf8'), 'generated bytes');
      assert.throws(() => reserveContentRoots(f.catalog, [f.to.id]), /progress/);
    } finally {
      release();
    }
    const scan = await f.app.inject({
      method: 'POST',
      url: `/api/v1/roots/${f.to.id}/scan`,
      headers: f.auth,
    });
    assert.equal(scan.statusCode, 200, scan.body);
    release = reserveContentRoots(f.catalog, [f.to.id]);
    release();
  } finally {
    await f.dispose();
  }
});

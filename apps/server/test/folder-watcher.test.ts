import assert from 'node:assert/strict';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import test from 'node:test';
import { setTimeout as pause } from 'node:timers/promises';
import { DomainError } from '@ecs/domain';
import { reserveContentRoots } from '../src/root-mutations.js';
import { libraryFixture } from './library-fixture.js';

async function eventually(check: () => boolean) {
  const deadline = Date.now() + 10_000;
  while (!check()) {
    assert.ok(Date.now() < deadline, 'Watcher did not update the catalog');
    await pause(40);
  }
}

test('opt-in recursive watchers preserve records and saved matches across folders without rescans', async () => {
  const f = await libraryFixture();
  try {
    const roots = [];
    for (const name of ['before', 'after']) {
      const path = join(f.base, name);
      await mkdir(path);
      roots.push(
        f.catalog.createContentRoot({
          path,
          label: name,
          libraryId: f.library.id,
          actorId: f.owner.id,
        }),
      );
    }
    const [old, target] = roots;
    assert.ok(old && target);
    await writeFile(join(old.path, 'generated.nes'), 'generated bytes');
    // Enabling watching indexes the initial state too; no scan endpoint is used.
    for (const root of roots) {
      const response = await f.app.inject({
        method: 'PUT',
        url: `/api/v1/roots/${root.id}/watching-policy`,
        headers: f.auth,
        payload: { enabled: true },
      });
      assert.equal(response.statusCode, 200, response.body);
    }
    await eventually(() => f.catalog.listSources(old.id).length === 1);
    const source = f.catalog.listSources(old.id)[0];
    assert.ok(source);
    const selection = {
      id: 'fixture',
      kind: 'metadata' as const,
      providerId: 'fixture',
      title: 'Saved game',
      confidence: 'name' as const,
      originKind: null,
      contentAvailable: false,
      contentType: null,
      fileName: null,
      updatedAt: '',
      metadata: {},
    };
    f.catalog.saveSourceMatch(source.id, 0, 'metadata', selection, null, f.owner.id);
    const saved = f.catalog.saveSourceMatch(
      source.id,
      1,
      'artwork',
      { ...selection, kind: 'artwork', contentAvailable: true, contentType: 'image/png' },
      Buffer.from('generated art'),
      f.owner.id,
    );
    await mkdir(join(target.path, 'new', 'nested'), { recursive: true });
    // A manual scan or organizer holding the sibling reservation must delay, not lose, events.
    let release: (() => void) | undefined;
    await eventually(() => {
      try {
        release = reserveContentRoots(f.catalog, [old.id]);
        return true;
      } catch (error) {
        if (error instanceof DomainError && error.code === 'root-busy') return false;
        throw error;
      }
    });
    assert.ok(release);
    try {
      await rename(
        join(old.path, 'generated.nes'),
        join(target.path, 'new', 'nested', 'renamed.nes'),
      );
      await pause(700);
      assert.equal(f.catalog.getSource(source.id)?.rootId, old.id);
    } finally {
      release();
    }
    await eventually(() => f.catalog.getSource(source.id)?.rootId === target.id);
    assert.equal(f.catalog.getSource(source.id)?.relativePath, 'new/nested/renamed.nes');
    assert.deepEqual(f.catalog.sourceMatches(source.id), saved);
    assert.deepEqual(
      f.catalog.sourceMatchContent(source.id, 'artwork'),
      new Uint8Array(Buffer.from('generated art')),
    );
    assert.equal(f.catalog.listSources(target.id).length, 1);
    for (const root of roots) {
      const response = await f.app.inject({
        method: 'PUT',
        url: `/api/v1/roots/${root.id}/watching-policy`,
        headers: f.auth,
        payload: { enabled: false },
      });
      assert.equal(response.statusCode, 200, response.body);
    }
    await rename(
      join(target.path, 'new', 'nested', 'renamed.nes'),
      join(target.path, 'stopped.nes'),
    );
    await pause(700);
    assert.equal(f.catalog.getSource(source.id)?.relativePath, 'new/nested/renamed.nes');
  } finally {
    await f.dispose();
  }
});

test('offline opted-in folder recovers through periodic reconciliation and shutdown cancels work', async (t) => {
  const f = await libraryFixture();
  const { FolderWatcher } = await import('../src/folder-watcher.js');
  const watcher = new FolderWatcher(f.catalog);
  t.mock.timers.enable({ apis: ['setInterval'] });
  try {
    const path = join(f.base, 'temporarily-offline');
    const root = f.catalog.createContentRoot({
      path,
      label: 'Offline fixture',
      libraryId: f.library.id,
      actorId: f.owner.id,
    });
    f.catalog.setFolderWatchPolicy(root.id, f.owner.id);
    watcher.reconcile();
    await eventually(() => watcher.status(root.id).state === 'offline');
    await mkdir(path);
    await writeFile(join(path, 'recovered.nes'), 'generated bytes');
    t.mock.timers.tick(30_000);
    await eventually(() => f.catalog.listSources(root.id).length === 1);
    assert.equal(watcher.status(root.id).state, 'watching');
    await watcher.close();
    await writeFile(join(path, 'after-close.nes'), 'generated bytes');
    t.mock.timers.tick(60_000);
    await pause(400);
    assert.equal(f.catalog.listSources(root.id).length, 1);
  } finally {
    await watcher.close();
    t.mock.timers.reset();
    await f.dispose();
  }
});

test('watch preferences resume after server restart and an unwatched folder stays untouched', async () => {
  const f = await libraryFixture();
  let restarted: Awaited<ReturnType<typeof import('../src/app.js').openServer>> | undefined;
  try {
    const path = join(f.base, 'persisted');
    await mkdir(path);
    const root = f.catalog.createContentRoot({
      path,
      label: 'Persisted',
      libraryId: f.library.id,
      actorId: f.owner.id,
    });
    const unobservedPath = join(f.base, 'unwatched');
    await mkdir(unobservedPath);
    const unobserved = f.catalog.createContentRoot({
      path: unobservedPath,
      label: 'Unwatched',
      libraryId: f.library.id,
      actorId: f.owner.id,
    });
    f.catalog.setFolderWatchPolicy(root.id, f.owner.id);
    await f.close();
    const { openServer } = await import('../src/app.js');
    restarted = await openServer({ dataDir: join(f.base, 'data') });
    await restarted.app.ready();
    await writeFile(join(path, 'after-restart.nes'), 'generated bytes');
    await writeFile(join(unobservedPath, 'not-indexed.nes'), 'generated bytes');
    const catalog = restarted.catalog;
    await eventually(() => catalog.listSources(root.id).length === 1);
    assert.equal(catalog.listSources(unobserved.id).length, 0);
  } finally {
    await restarted?.close();
    await f.dispose();
  }
});

test('healthy watchers audit infrequently instead of rescanning unchanged libraries every 30 seconds', async (t) => {
  const f = await libraryFixture();
  const { FolderWatcher } = await import('../src/folder-watcher.js');
  const watcher = new FolderWatcher(f.catalog);
  t.mock.timers.enable({ apis: ['setInterval', 'Date'] });
  try {
    const path = join(f.base, 'healthy-watch');
    await mkdir(path);
    await writeFile(join(path, 'fixture.nes'), 'generated bytes');
    const root = f.catalog.createContentRoot({
      path,
      label: 'Healthy',
      libraryId: f.library.id,
      actorId: f.owner.id,
    });
    f.catalog.setFolderWatchPolicy(root.id, f.owner.id);
    watcher.reconcile();
    await eventually(
      () =>
        watcher.status(root.id).state === 'watching' &&
        !!watcher.status(root.id).lastScanAt &&
        f.catalog.listSources(root.id).length === 1,
    );
    const count = () =>
      f.catalog.libraryJobs.list(100).filter((job) => job.scope.rootId === root.id).length;
    // Drain any delayed filesystem notification from fixture creation.
    t.mock.timers.tick(2_000);
    await pause(350);
    const baseline = count();
    t.mock.timers.tick(30_000);
    await pause(150);
    assert.equal(count(), baseline, 'No full scan for an unchanged healthy watcher');
    t.mock.timers.tick(15 * 60_000);
    await eventually(() => count() > baseline);
    await watcher.close();
  } finally {
    await watcher.close();
    t.mock.timers.reset();
    await f.dispose();
  }
});

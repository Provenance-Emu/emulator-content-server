import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { mkdtemp, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { boundedZipFingerprint } from '../src/matching-files.js';
import { generatedZip } from './matching-zip-fixture.js';

for (const deflate of [false, true])
  test(`single-ROM ZIP hashes the verified ${deflate ? 'deflated' : 'stored'} inner bytes without extraction`, async (t) => {
    const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
    t.after(() => rm(directory, { recursive: true, force: true }));
    const path = join(directory, 'generated.zip'),
      bytes = Buffer.from('123456789');
    await writeFile(
      path,
      generatedZip([
        { name: 'folder/generated.j64', bytes, deflate },
        { name: 'readme.txt', bytes: Buffer.from('Generated archive') },
      ]),
    );
    assert.deepEqual(await boundedZipFingerprint(path), {
      md5: createHash('md5').update(bytes).digest('hex'),
      crc32: 'cbf43926',
      size: 9,
    });
    assert.deepEqual(await readdir(directory), ['generated.zip']);
  });

test('ZIP matching declines ambiguous, nested, disc-layout, unsafe, encrypted, malformed, unsupported, or over-budget entries', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip');
  const bytes = Buffer.from('Generated bytes');
  const cases = [
    [
      { name: 'a.j64', bytes },
      { name: 'b.j64', bytes },
    ],
    [{ name: 'readme.txt', bytes }],
    [{ name: 'game.zip', bytes: generatedZip([{ name: 'inside.j64', bytes }]) }],
    [
      { name: 'game.bin', bytes },
      { name: 'game.cue', bytes },
    ],
    [{ name: '../escape.j64', bytes }],
    [{ name: '/absolute.j64', bytes }],
    [{ name: 'encrypted.j64', bytes, flags: 1 }],
    [{ name: 'strong-encrypted.j64', bytes, flags: 0x40 }],
    [{ name: 'masked-header.j64', bytes, flags: 0x2000 }],
    [{ name: 'unsupported.j64', bytes, method: 99 }],
    [{ name: 'too-large.j64', bytes, deflate: true, declaredSize: 64 * 1024 * 1024 + 1 }],
    [{ name: 'bomb.j64', bytes: Buffer.alloc(256 * 1024), deflate: true }],
    [{ name: 'crc.j64', bytes, declaredCrc: 0 }],
    [{ name: 'wrong-length.j64', bytes, deflate: true, declaredSize: bytes.length - 1 }],
    [
      {
        name: 'trailing.j64',
        bytes,
        deflate: true,
        compressedBytes: Buffer.concat([
          (await import('node:zlib')).deflateRawSync(bytes),
          Buffer.from([0]),
        ]),
      },
    ],
    Array.from({ length: 257 }, (_, index) => ({ name: `${index}.txt`, bytes })),
  ];
  for (const members of cases) {
    await writeFile(path, generatedZip(members));
    assert.equal(await boundedZipFingerprint(path), null, members[0]?.name);
  }
  const padded = generatedZip([{ name: 'generated.j64', bytes }]);
  const end = Buffer.from(padded.subarray(-22));
  end.writeUInt32LE(end.readUInt32LE(12) + 1024 * 1024 + 1, 12);
  await writeFile(
    path,
    Buffer.concat([padded.subarray(0, -22), Buffer.alloc(1024 * 1024 + 1), end]),
  );
  assert.equal(
    await boundedZipFingerprint(path),
    null,
    'Central directory metadata must remain bounded',
  );
  const { truncate } = await import('node:fs/promises');
  await truncate(path, 64 * 1024 * 1024 + 1);
  assert.equal(
    await boundedZipFingerprint(path),
    null,
    'Compressed container bytes must remain bounded',
  );
  await writeFile(path, Buffer.from('not an archive'));
  assert.equal(await boundedZipFingerprint(path), null);
});

test('inner ZIP hashing is cancellable before and during bounded streaming', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip');
  await writeFile(
    path,
    generatedZip([{ name: 'generated.j64', bytes: randomBytes(8 * 1024 * 1024), deflate: true }]),
  );
  const before = new AbortController();
  before.abort();
  await assert.rejects(boundedZipFingerprint(path, before.signal), { name: 'AbortError' });
  const during = new AbortController(),
    pending = boundedZipFingerprint(path, during.signal);
  setTimeout(() => during.abort(), 1);
  await assert.rejects(pending, { name: 'AbortError' });
});

test('ZIP hashing rejects an outer identity change between index selection and content hashing', async (t) => {
  const { utimesSync } = await import('node:fs');
  const { fingerprintSingleZipEntry } = await import('@ecs/storage');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip');
  await writeFile(
    path,
    generatedZip([{ name: 'generated.j64', bytes: Buffer.from('Generated data') }]),
  );
  await assert.rejects(
    fingerprintSingleZipEntry(
      path,
      {
        maxExpandedBytes: 64 * 1024 * 1024,
        maxCompressionRatio: 100,
        maxEntries: 256,
        maxNesting: 1,
        timeoutMs: 1000,
      },
      (names) => {
        utimesSync(path, new Date(), new Date(Date.now() + 10000));
        return names[0] ?? null;
      },
    ),
    (error) => error instanceof Error && 'code' in error && error.code === 'archive-changed',
  );
});

test('ZIP lookup uses inner hashes and a versioned cache; ambiguous and encrypted archives cannot auto-save even a provider checksum claim', async () => {
  const { mkdir } = await import('node:fs/promises');
  const { setTimeout: pause } = await import('node:timers/promises');
  const { libraryFixture } = await import('./library-fixture.js');
  const { sourceMetadata } = await import('../src/source-metadata.js');
  const plugins = await mkdtemp(join(tmpdir(), 'ecs-zip-provider-'));
  await mkdir(join(plugins, 'provider'));
  await writeFile(
    join(plugins, 'provider', 'plugin.json'),
    JSON.stringify({
      id: 'test.zip',
      name: 'Generated ZIP evidence fixture',
      kind: 'provider',
      version: '1',
      engine: 'ecs.plugin/1',
      entry: 'entry.mjs',
      provider: { capabilities: ['metadata'], network: false },
    }),
  );
  await writeFile(
    join(plugins, 'provider', 'entry.mjs'),
    `export default {search:async input=>[{id:'generated',kind:'metadata',title:'Generated checksum claim',confidence:'checksum',metadata:{systemId:'com.provenance.jaguar',md5:input.md5??'none',crc32:input.crc32??'none',size:String(input.size)}}]};`,
  );
  const f = await libraryFixture({ matchingPluginsDir: plugins });
  try {
    const directory = join(f.base, 'generated');
    await mkdir(directory);
    const path = join(directory, 'single.zip');
    await writeFile(
      path,
      generatedZip([{ name: 'generated.j64', bytes: Buffer.from('123456789'), deflate: true }]),
    );
    await writeFile(
      join(directory, 'ambiguous.zip'),
      generatedZip([
        { name: 'a.j64', bytes: Buffer.from('a') },
        { name: 'b.j64', bytes: Buffer.from('b') },
      ]),
    );
    await writeFile(
      join(directory, 'encrypted.zip'),
      generatedZip([{ name: 'generated.j64', bytes: Buffer.from('encrypted'), flags: 1 }]),
    );
    const root = f.catalog.createContentRoot({
      path: directory,
      label: 'Generated',
      libraryId: f.library.id,
      actorId: f.owner.id,
    });
    const scan = await f.app.inject({
      method: 'POST',
      url: `/api/v1/roots/${root.id}/scan`,
      headers: f.auth,
    });
    assert.equal(scan.statusCode, 200, scan.body);
    const single = f.catalog
      .listSources(root.id)
      .find((source) => source.displayName === 'single.zip');
    assert.ok(single);
    const etag = (await sourceMetadata(path, single.id)).etag;
    f.catalog.saveMatchingFingerprint(single.id, etag, {
      md5: 'a'.repeat(32),
      crc32: '00000000',
      size: 99,
    });
    const stamps: string[] = [];
    const read = f.catalog.matchingFingerprint.bind(f.catalog);
    let hits = 0;
    f.catalog.matchingFingerprint = (id, key) => {
      stamps.push(key);
      const cached = read(id, key);
      if (cached) hits++;
      return cached;
    };
    const lookup = () =>
      f.app.inject({
        method: 'POST',
        url: `/api/v1/sources/${single.id}/matches`,
        headers: f.auth,
        payload: { checksum: true, providerIds: ['test.zip'] },
      });
    const first = await lookup();
    assert.equal(first.statusCode, 200, first.body);
    const candidate = first.json().candidates[0];
    assert.equal(candidate.metadata.md5, createHash('md5').update('123456789').digest('hex'));
    assert.equal(candidate.metadata.crc32, 'cbf43926');
    assert.equal(candidate.metadata.size, '9');
    assert.equal(hits, 0);
    assert.ok(stamps.every((stamp) => stamp.startsWith('zip-v1:')));
    assert.equal((await lookup()).statusCode, 200);
    assert.equal(hits, 1);
    await writeFile(
      path,
      generatedZip([{ name: 'generated.j64', bytes: Buffer.from('987654321'), deflate: true }]),
    );
    const stale = await f.app.inject({
      method: 'PUT',
      url: `/api/v1/sources/${single.id}/matches/selections`,
      headers: f.auth,
      payload: {
        requestId: first.json().requestId,
        candidateId: candidate.id,
        expectedRevision: 0,
      },
    });
    assert.equal(stale.statusCode, 409, stale.body);
    const changed = await lookup();
    assert.equal(changed.statusCode, 200, changed.body);
    assert.equal(
      changed.json().candidates[0].metadata.md5,
      createHash('md5').update('987654321').digest('hex'),
    );
    assert.equal(hits, 1);
    const created = await f.app.inject({
      method: 'POST',
      url: '/api/v1/library-jobs',
      headers: f.auth,
      payload: {
        kind: 'match',
        rootId: root.id,
        options: { checksum: true, providerIds: ['test.zip'] },
      },
    });
    assert.equal(created.statusCode, 202, created.body);
    const deadline = Date.now() + 5000;
    while (f.catalog.libraryJobs.get(created.json().job.id)?.state !== 'completed') {
      assert.ok(Date.now() < deadline, 'ZIP matching job did not settle');
      await pause(5);
    }
    const job = f.catalog.libraryJobs.get(created.json().job.id);
    assert.equal(job?.saved, 1);
    assert.equal(job?.review, 2);
    assert.equal(job?.failed, 0);
    assert.equal(
      f.catalog.sourceMatches(single.id).matches[0]?.metadata.md5,
      createHash('md5').update('987654321').digest('hex'),
    );
    for (const source of f.catalog.listSources(root.id).filter((source) => source.id !== single.id))
      assert.deepEqual(f.catalog.sourceMatches(source.id).matches, []);
  } finally {
    await f.dispose();
    await rm(plugins, { recursive: true, force: true });
  }
});

test('local encryption flags cannot hide behind an unencrypted central record', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip');
  for (const flag of [0x40, 0x2000]) {
    const zip = generatedZip([{ name: 'generated.j64', bytes: Buffer.from('123456789') }]);
    zip.writeUInt16LE(flag, 6);
    await writeFile(path, zip);
    assert.equal(await boundedZipFingerprint(path), null);
  }
});

test('ZIP hashing rejects replacement of the outer path even when replacement bytes are identical', async (t) => {
  const { renameSync, writeFileSync } = await import('node:fs');
  const { fingerprintSingleZipEntry } = await import('@ecs/storage');
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip'),
    zip = generatedZip([{ name: 'generated.j64', bytes: Buffer.from('123456789') }]);
  await writeFile(path, zip);
  await assert.rejects(
    fingerprintSingleZipEntry(
      path,
      {
        maxExpandedBytes: 64 * 1024 * 1024,
        maxCompressionRatio: 100,
        maxEntries: 256,
        maxNesting: 1,
        timeoutMs: 1000,
      },
      (names) => {
        renameSync(path, join(directory, 'prior.zip'));
        writeFileSync(path, zip);
        return names[0] ?? null;
      },
    ),
    (error) => error instanceof Error && 'code' in error && error.code === 'archive-changed',
  );
});

test('a ZIP symlink entry is not fingerprinted as a regular inner ROM', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ecs-zip-fingerprint-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const path = join(directory, 'generated.zip');
  const zip = generatedZip([{ name: 'generated.j64', bytes: Buffer.from('123456789') }]);
  const central = zip.readUInt32LE(zip.length - 6);
  zip.writeUInt16LE(0x314, central + 4);
  zip.writeUInt32LE(0xa1ff0000, central + 38);
  await writeFile(path, zip);
  assert.equal(await boundedZipFingerprint(path), null);
});

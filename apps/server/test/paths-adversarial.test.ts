import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { issueToken } from '@ecs/auth';
import { openServer } from '../src/index.js';

test('unsafe upload paths leave staged bytes and the item unchanged', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ecs-unsafe-paths-'));
  let server: Awaited<ReturnType<typeof openServer>> | undefined;
  t.after(async () => {
    try {
      await server?.close();
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
  server = await openServer({ dataDir: dir, localTrust: false });
  const { app } = server;
  const bootstrap = issueToken();
  server.catalog.saveBootstrapHash(bootstrap.hash);
  const owner = await app.inject({
    method: 'POST',
    url: '/api/v1/auth/bootstrap',
    payload: { token: bootstrap.token, username: 'owner', password: 'correct-horse' },
  });
  assert.equal(owner.statusCode, 201);
  const headers = { authorization: `Bearer ${owner.json().token}` };
  const libraries = await app.inject({ url: '/api/v1/libraries', headers });
  assert.equal(libraries.statusCode, 200);
  const libraryId = libraries.json().items[0].id as string;
  const created = await app.inject({
    method: 'POST',
    url: '/api/v1/items',
    headers,
    payload: { libraryId, systemIdentifier: 'com.provenance.nes', title: 'Path validation' },
  });
  assert.equal(created.statusCode, 201);
  const item = created.json() as { id: string; revision: number };
  const upload = await app.inject({
    method: 'POST',
    url: '/api/v1/uploads',
    headers,
    payload: { libraryId },
  });
  assert.equal(upload.statusCode, 201);
  const uploadUrl = `/api/v1/uploads/${upload.json().id}`;
  const put = await app.inject({
    method: 'PUT',
    url: `${uploadUrl}/content`,
    headers: { ...headers, 'content-type': 'application/octet-stream' },
    payload: Buffer.from('generated bytes'),
  });
  assert.equal(put.statusCode, 204);
  const complete = (relativePath: string) =>
    app.inject({
      method: 'POST',
      url: `${uploadUrl}/complete`,
      headers,
      payload: {
        itemId: item.id,
        kind: 'rom',
        displayName: 'generated.bin',
        relativePath,
        baseRevision: item.revision,
      },
    });
  for (const input of [
    { name: 'parent traversal', path: '../outside.bin' },
    { name: 'nested traversal', path: 'saves/../../outside.bin' },
    { name: 'Windows traversal', path: 'saves\\..\\outside.bin' },
    { name: 'mixed separators', path: 'saves/..\\outside.bin' },
    { name: 'POSIX absolute path', path: '/outside.bin' },
    { name: 'Windows absolute path', path: 'C:\\outside.bin' },
    { name: 'Windows drive-relative path', path: 'C:outside.bin' },
    { name: 'UNC path', path: '\\\\server\\share\\outside.bin' },
    { name: 'current directory segment', path: 'saves/./file.bin' },
    { name: 'empty segment', path: 'saves//file.bin' },
    { name: 'NUL byte', path: 'saves/hidden\0.bin' },
    { name: '1025-character path', path: `${'a/'.repeat(510)}b.bin` },
  ]) {
    await t.test(input.name, async () => {
      const rejected = await complete(input.path);
      assert.equal(rejected.statusCode, 400, rejected.body);
      assert.equal(rejected.json().type, 'urn:ecs:problem:invalid-body');
      const state = await app.inject({ url: uploadUrl, headers });
      assert.equal(state.statusCode, 200);
      assert.equal(state.json().state, 'open');
      assert.equal(state.json().received, 15);
      const manifest = await app.inject({ url: `/api/v1/items/${item.id}/manifest`, headers });
      assert.equal(manifest.statusCode, 200);
      assert.equal(manifest.json().revision, item.revision);
      assert.deepEqual(manifest.json().files, []);
    });
  }
  const boundaryPath = `${'a/'.repeat(510)}x.bi`;
  const accepted = await complete(boundaryPath);
  assert.equal(accepted.statusCode, 201, accepted.body);
  assert.equal(accepted.json().relativePath, boundaryPath);
  const content = await app.inject({ url: `/api/v1/files/${accepted.json().id}/content`, headers });
  assert.equal(content.statusCode, 200);
  assert.equal(content.body, 'generated bytes');
});

test('successful adoption disables stale revision actions until a follow-up read succeeds', async (t) => {
  let changed = false;
  let recover = false;
  const f = transport((url) => {
    if (url.pathname.endsWith('/adopt')) {
      changed = true;
      return Response.json({ ...asset(), revision: 99, conflictOf: null });
    }
    if (changed && !recover) return problem(503);
    if (url.pathname.endsWith('/manifest'))
      return Response.json({
        version: 1,
        itemId: 'item',
        revision: changed ? 18 : 17,
        files: [file('asset', changed ? null : 'live')],
      });
    return Response.json({ ...asset(), conflictOf: changed ? null : 'live' });
  });
  t.after(f.restore);
  const d = createDetail(f.client, { ...entry('asset', 'asset'), canAdopt: true, canUpload: true });
  t.after(() => d.dispose());
  await d.load();
  assert.equal((await d.adopt())?.revision, 99);
  assert.equal(get(d).canAdopt, false);
  assert.equal(get(d).canUpload, false);
  assert.equal(get(d).revision, null);
  recover = true;
  await d.load();
  assert.equal(get(d).revision, 18);
  assert.equal(get(d).canUpload, true);
  assert.equal(get(d).canAdopt, false);
});


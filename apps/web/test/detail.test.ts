test('item details load only its manifest and use current item revision, retaining all save copies', async (t) => {
  const f = transport((url) => {
    assert.equal(url.pathname, '/api/v1/items/item/manifest');
    return Response.json({
      version: 1,
      itemId: 'item',
      revision: 19,
      files: [file(), file('copy', 'live')],
    });
  });
  t.after(f.restore);
  const d = createDetail(f.client, entry());
  t.after(() => d.dispose());
  await d.load();
  assert.equal(get(d).revision, 19);
  assert.equal(get(d).item?.revision, 19);
  assert.equal(get(d).files.length, 2);
  assert.equal(get(d).canUpload, false);
  assert.equal(get(d).canAdopt, false);
});

test('source download uses only the typed endpoint and returns original filename and generated bytes', async (t) => {
  const e = entry('source', 'id & source');
  assert.ok(e.source);
  e.source.name = 'original.nes';
  e.source.contentPath = '/ignored/for/download';
  const f = transport((url) => {
    assert.equal(url.pathname, '/api/v1/sources/id%20%26%20source/content');
    return new Response(new Uint8Array([1, 2, 3]), {
      headers: { 'content-length': '3', etag: '"source-1"' },
    });
  });
  t.after(f.restore);
  const d = createDetail(f.client, e);
  t.after(() => d.dispose());
  await d.load();
  const downloaded = await d.download();
  assert.equal(downloaded?.name, 'original.nes');
  assert.deepEqual(downloaded?.bytes, new Uint8Array([1, 2, 3]));
  assert.equal(get(d).reading, null);
  assert.equal(get(d).canAdopt, false);
});

test('managed downloads allow only current manifest files and expose transfer progress', async (t) => {
  const bytes = deferred<Uint8Array>();
  const f = transport((url) =>
    url.pathname.endsWith('/manifest')
      ? Response.json({ version: 1, itemId: 'item', revision: 9, files: [file()] })
      : new Response(
          new ReadableStream({
            async start(controller) {
              controller.enqueue(await bytes.promise);
              controller.close();
            },
          }),
          { headers: { 'content-length': '3', etag: '"asset-1"' } },
        ),
  );
  t.after(f.restore);
  const d = createDetail(f.client, entry());
  t.after(() => d.dispose());
  await d.load();
  assert.equal(await d.download(file('other')), null);
  assert.equal(f.requests.length, 1);
  const states: number[] = [];
  const unsubscribe = d.subscribe((s) => {
    if (s.reading) states.push(s.reading.received);
  });
  t.after(unsubscribe);
  const downloading = d.download(file());
  bytes.resolve(new Uint8Array([4, 5, 6]));
  const result = await downloading;
  assert.equal(result?.name, 'save.sav');
  assert.deepEqual(result?.bytes, new Uint8Array([4, 5, 6]));
  assert.ok(states.includes(3));
});

test('only explicit server canAdopt permits choosing selected save copy, then refreshes current item revision', async (t) => {
  let adopted = false;
  const f = transport((url, init) => {
    if (url.pathname.endsWith('/adopt')) {
      assert.equal(init?.method, 'POST');
      adopted = true;
      return Response.json({ ...asset(), conflictOf: null, revision: 88 });
    }
    if (url.pathname.endsWith('/manifest'))
      return Response.json({
        version: 1,
        itemId: 'item',
        revision: adopted ? 11 : 10,
        files: [file('asset', adopted ? null : 'live'), file('old-live', 'asset')],
      });
    return Response.json({ ...asset(), conflictOf: adopted ? null : 'live' });
  });
  t.after(f.restore);
  const e = entry('asset', 'asset');
  const reader = createDetail(f.client, e);
  t.after(() => reader.dispose());
  await reader.load();
  assert.equal(await reader.adopt(), null);
  assert.equal(adopted, false);
  const d = createDetail(f.client, { ...e, canUpload: true, canAdopt: true });
  t.after(() => d.dispose());
  await d.load();
  assert.equal(get(d).canAdopt, true);
  assert.equal((await d.adopt())?.revision, 88);
  assert.equal(get(d).revision, 11);
  assert.equal(get(d).item?.revision, 11);
  assert.equal(get(d).canAdopt, false);
  assert.equal(get(d).files.length, 2);
});

test('detail access errors clear private data while transient refreshes preserve it', async (t) => {
  let status = 200;
  const f = transport(() =>
    status === 200
      ? Response.json({ version: 1, itemId: 'item', revision: 9, files: [file()] })
      : problem(status),
  );
  t.after(f.restore);
  const d = createDetail(f.client, { ...entry(), canUpload: true });
  t.after(() => d.dispose());
  await d.load();
  status = 503;
  await d.load();
  assert.equal(get(d).files.length, 1);
  for (status of [401, 403, 404]) {
    await d.load();
    assert.equal(get(d).entry, null);
    assert.equal(get(d).item, null);
    assert.deepEqual(get(d).files, []);
    assert.equal(get(d).canUpload, false);
    status = 200;
    await d.load();
  }
});

test('disposed detail suppresses late loads, downloads, progress and adoption results', async (t) => {
  const response = deferred<Response>();
  const f = transport(() => response.promise);
  t.after(f.restore);
  const d = createDetail(f.client, entry());
  const load = d.load();
  await Promise.resolve();
  assert.equal(f.requests.length, 1);
  d.dispose();
  response.resolve(Response.json({ version: 1, itemId: 'item', revision: 20, files: [file()] }));
  await load;
  assert.equal(get(d).entry, null);
  assert.deepEqual(get(d).files, []);
  const bytes = deferred<Response>();
  const g = transport(() => bytes.promise);
  t.after(g.restore);
  const s = createDetail(g.client, entry('source', 'source'));
  await s.load();
  const download = s.download();
  s.dispose();
  bytes.resolve(new Response(new Uint8Array([1, 2, 3])));
  assert.equal(await download, null);
  assert.equal(get(s).reading, null);
  const mutation = deferred<Response>();
  const h = transport((url) =>
    url.pathname.endsWith('/adopt')
      ? mutation.promise
      : url.pathname.endsWith('/manifest')
        ? Response.json({
            version: 1,
            itemId: 'item',
            revision: 10,
            files: [file('asset', 'live')],
          })
        : Response.json(asset()),
  );
  t.after(h.restore);
  const a = createDetail(h.client, { ...entry('asset', 'asset'), canAdopt: true });
  await a.load();
  const adopt = a.adopt();
  a.dispose();
  mutation.resolve(Response.json(asset()));
  assert.equal(await adopt, null);
  assert.equal(get(a).asset, null);
  assert.equal(h.requests.length, 3);
});


import assert from 'node:assert/strict';
import test from 'node:test';
import { type DownloadSink, sha256Bytes, type WebPlayerDescriptor } from '@ecs/client';
import { CHUNK_BYTES, type PlayerContentChunks } from '../src/player/content-chunks.js';
import { startPlayer } from '../src/player/controller.js';
import { fixture } from './player-fixture.js';

async function dreamcast(id: string, size: number) {
  const f = fixture();
  const resources = await f.client.playerCoreAssets(f.core.id);
  const profile: WebPlayerDescriptor = {
    profileVersion: 1,
    id,
    name: 'Generated Dreamcast player',
    systems: ['com.provenance.dreamcast'],
    runtime: 'retroarch-emscripten-esm',
    filesystem: 'memfs',
    threaded: false,
    saveCompletion: 'none',
    contentExtensions: ['chd', 'cdi', 'elf', 'zip'],
    // The emulator's own limit for a file held as one buffer.
    maxContentBytes: 32 * 1024 ** 2,
    buildVersion: 'Generated fixture',
    loader: { ...f.core.loader, sha256: await sha256Bytes(resources.loader.bytes) },
    wasm: { ...f.core.wasm, sha256: await sha256Bytes(resources.wasm.bytes) },
    assets: [],
  };
  f.item.systemIdentifier = f.source.systemId = 'com.provenance.dreamcast';
  f.source.name = 'disc.chd';
  f.source.size = size;
  f.client.playerProfile = async () => profile;
  f.client.playerProfileAssets = async () => ({ ...resources, assets: [] });
  f.client.sources = async () => ({ items: [f.source] });
  let mounted: { path: string; chunks: PlayerContentChunks } | undefined;
  f.runtime.mountContentChunks = async (path, chunks) => {
    f.events.push(`mount-chunks:${path}`);
    mounted = { path, chunks: { size: chunks.size, parts: [...chunks.parts] } };
  };
  // Generated bytes, sent in sizes that never line up with a piece boundary.
  f.client.downloadSourceTo = async (_id: string, sink: DownloadSink) => {
    f.events.push('download:source');
    await sink.reset();
    const block = new Uint8Array(3_000_017);
    for (let sent = 0; sent < size; sent += block.byteLength) {
      const part = block.subarray(0, Math.min(block.byteLength, size - sent));
      part[0] = (sent / block.byteLength) & 0xff;
      await sink.write(part);
    }
    await sink.close();
  };
  return { ...f, profile, mounted: () => mounted };
}

test('a Dreamcast disc larger than the one-buffer limit is handed to Flycast in pieces', async () => {
  const size = 70 * 1024 ** 2 + 5;
  const f = await dreamcast('org.flycast.wasm-jit', size);
  await startPlayer(
    f.client,
    { kind: 'source', sourceId: 'source' },
    { canvas: {} as HTMLCanvasElement, importer: f.importer, profileId: f.profile.id },
  );
  const mounted = f.mounted();
  assert.ok(mounted);
  assert.equal(mounted.path, '/ecs/content/game.chd');
  assert.equal(mounted.chunks.size, size);
  assert.equal(mounted.chunks.parts.length, Math.ceil(size / CHUNK_BYTES));
  assert.equal(mounted.chunks.parts.at(-1)?.byteLength, size % CHUNK_BYTES);
  // The disc is never also written as one buffer, and it is attached before the game starts.
  assert.ok(!f.events.includes('write:/ecs/content/game.chd'));
  assert.ok(!f.events.includes('collect:source'));
  assert.ok(f.events.indexOf('mount-chunks:/ecs/content/game.chd') < f.events.indexOf('main'));
});

test('an emulator that was not shown to read by seeking keeps its own limit', async () => {
  const f = await dreamcast('org.libretro.parallel-dc', 70 * 1024 ** 2);
  await assert.rejects(
    startPlayer(
      f.client,
      { kind: 'source', sourceId: 'source' },
      { canvas: {} as HTMLCanvasElement, importer: f.importer, profileId: f.profile.id },
    ),
    /This file is 70 MB\. This emulator can load up to 32 MB/,
  );
  assert.equal(f.mounted(), undefined);
  assert.ok(!f.events.includes('download:source'));
});

test('a disc beyond what a browser can hold is refused before any of it is downloaded', async () => {
  const f = await dreamcast('org.flycast.wasm-jit', 3 * 1024 ** 3);
  await assert.rejects(
    startPlayer(
      f.client,
      { kind: 'source', sourceId: 'source' },
      { canvas: {} as HTMLCanvasElement, importer: f.importer, profileId: f.profile.id },
    ),
    /This file is 3\.0 GB\. This emulator can load up to 2\.0 GB/,
  );
  assert.ok(!f.events.includes('download:source'));
});
